const INITIALS = ['zh', 'ch', 'sh', 'b', 'p', 'm', 'f', 'd', 't', 'n', 'l', 'g', 'k', 'h', 'j', 'q', 'x', 'r', 'z', 'c', 's', 'y', 'w'];

/* 拆分音节为声母 + 韵母（处理 j/q/x/y 后面省略两点的 ü） */
function splitSyl(s) {
  for (var i = 0; i < INITIALS.length; i++) {
    var ini = INITIALS[i];
    if (s.indexOf(ini) === 0 && s.length > ini.length) {
      var rest = s.slice(ini.length);
      if ((ini === 'j' || ini === 'q' || ini === 'x' || ini === 'y') && rest.charAt(0) === 'u') {
        rest = 'ü' + rest.slice(1);
      }
      return { sm: ini, ym: rest };
    }
  }
  return { sm: '', ym: s };
}

/* 韵母 24 个（不含派生复韵母），用于判断三拼音节 */
const FINALS = ['a', 'o', 'e', 'i', 'u', 'ü', 'ai', 'ei', 'ui', 'ao', 'ou', 'iu', 'ie', 'üe', 'er', 'an', 'en', 'in', 'un', 'ün', 'ang', 'eng', 'ing', 'ong'];

/* 拆成 声母 + 介音 + 韵母：jia 这类三拼音节要单独显示，不能当成 j + ia */
function splitSyl3(s) {
  var p = splitSyl(s);
  var rest = p.ym;
  if (p.sm && rest.length > 1 && FINALS.indexOf(rest) < 0) {
    var med = rest.charAt(0);
    var fin = rest.slice(1);
    if ('iuü'.indexOf(med) >= 0 && FINALS.indexOf(fin) >= 0) {
      return { sm: p.sm, med: med, ym: fin, three: true };
    }
  }
  return { sm: p.sm, med: '', ym: rest, three: false };
}

/* 某个声母能拼的音节 */
function sylsForInitial(ini) {
  return Object.keys(SYL).filter(function (s) { return splitSyl(s).sm === ini; });
}
/* 某个韵母能拼的音节 */
function sylsForFinal(fin) {
  return Object.keys(SYL).filter(function (s) { return splitSyl(s).ym === fin; });
}

